#!/usr/bin/env node
/**
 * Vendor tool: derives the offline activation verifier from a code.
 *
 *   node scripts/gen-activation-verifier.mjs <16-digit-code>
 *
 * Writes src/main/core/activationSecret.ts containing ONLY the scrypt-derived
 * verifier (salt + hash) — the activation code itself is never stored anywhere
 * in this repository, bundle, database, or logs (see docs/SECURITY_MODEL.md §6).
 * Keep the code private: deliver it to the customer out-of-band.
 */
import { randomBytes, scryptSync } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const code = String(process.argv[2] ?? '').replace(/\D/g, '')

if (code.length < 6 || code.length > 32) {
  console.error('Usage: node scripts/gen-activation-verifier.mjs <activation-code (6-32 digits)>')
  process.exit(1)
}

// Must mirror ACTIVATION_PARAMS in src/main/core/activationSecret.ts.
const PARAMS = { N: 16384, r: 8, p: 1, keylen: 32 }

const salt = randomBytes(16)
const verifier = scryptSync(code, salt, PARAMS.keylen, { N: PARAMS.N, r: PARAMS.r, p: PARAMS.p })
const fingerprint = scryptSync(verifier, Buffer.alloc(0), 8).toString('hex').slice(0, 16)

const out = `/**
 * DERIVED ACTIVATION VERIFIER — do not edit.
 * Generated by scripts/gen-activation-verifier.mjs. Contains only a scrypt-derived
 * verifier (salt + hash) — the activation code itself is never stored anywhere
 * in this repository, bundle, database, or logs (see docs/SECURITY_MODEL.md §6).
 */
export const ACTIVATION_SALT = '${salt.toString('base64')}'
export const ACTIVATION_VERIFIER = '${verifier.toString('base64')}'
export const ACTIVATION_FINGERPRINT = '${fingerprint}'
export const ACTIVATION_PARAMS = { N: ${PARAMS.N}, r: ${PARAMS.r}, p: ${PARAMS.p}, keylen: ${PARAMS.keylen} }
`

writeFileSync(join(root, 'src/main/core/activationSecret.ts'), out)
console.log('Verifier written to src/main/core/activationSecret.ts')
console.log(`Fingerprint: ${fingerprint}`)
console.log('IMPORTANT: store the activation code in your vendor records — it cannot be recovered from this file.')
